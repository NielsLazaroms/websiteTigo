export interface Photo {
  /** Fallback source: the middle WebP size. */
  src: string;
  /** All WebP sizes, for the browser to choose from. */
  srcset: string;
  /** The untouched JPEG, used for the share-preview image. */
  original: string;
  alt: string;
  width: number;
  height: number;
}

/** Widths generated by `npm run images` (scripts/optimize-images.mjs). */
const PHOTO_WIDTHS = [400, 660, 800, 960, 1200];

